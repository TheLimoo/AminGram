// ==AminGramPlugin==
// @id          qr-maker
// @name        QR Maker
// @version     1.1
// @author      Amin
// @description /qr <text or link> posts a QR code image for it (qrserver.com). If the image cannot be sent, the QR image link is posted instead.
// @icon        sparkles
// @capabilities commands, send, http, file, settings
// @minPlatform 2
// ==/AminGramPlugin==

var PLUGIN_PAGE = [
  { type: "info", text: "QR images are generated by qrserver.com and posted as real photos; if a photo can't be sent, its link is posted instead." },
  { type: "action", id: "usage", title: "How to use", subtitle: "The one command this plugin has" },
  { type: "action", id: "stats", title: "Show statistics", subtitle: "QR codes made, sent as photos, link fallbacks" },
  { type: "action", id: "clear-stats", title: "Clear statistics", subtitle: "Zero the counters" }
];

// QR images come from the keyless goqr.me (qrserver) API — the
// plugin never downloads anything itself: amin.sendFile(url, opts)
// fetches and posts the image. sendFile is SYNCHRONOUS and returns
// a boolean; false (or the bridge missing it, i.e. no `file`
// capability) falls back to posting the image URL as a plain link.
var QR_API = "https://api.qrserver.com/v1/create-qr-code/?size=512x512&margin=10&data=";
var MAX_TEXT = 1000;

// sendFile BLOCKS inside the hook's ~5 s budget while it
// downloads. Nothing meaningful may run after it in the same
// invocation, so every post-send step (stats, fallback reply)
// is handed to a fresh budgeted callback via this tick.
var BUDGET_TICK_URL = "https://www.gstatic.com/generate_204";

var statsCache = null;

function dbAvailable() {
  try {
    return !!(amin.db && typeof amin.db.get === "function"
      && typeof amin.db.put === "function");
  } catch (e) { return false; }
}

function loadJsonStorage(key) {
  try {
    if (amin.storage && typeof amin.storage.getJSON === "function") {
      var v = amin.storage.getJSON(key, null);
      if (v && typeof v === "object") return v;
    }
  } catch (e) { /* fall through to raw parse */ }
  try {
    var raw = amin.storage.get(key, "");
    if (raw) {
      var parsed = JSON.parse(String(raw));
      if (parsed && typeof parsed === "object") return parsed;
    }
  } catch (e) { /* no legacy value */ }
  return null;
}

function saveJsonStorage(key, value) {
  try {
    if (amin.storage && typeof amin.storage.setJSON === "function") {
      amin.storage.setJSON(key, value);
      return;
    }
  } catch (e) { /* fall through */ }
  try { amin.storage.set(key, JSON.stringify(value)); } catch (e) {}
}

function nonNeg(n) {
  n = Number(n);
  return isFinite(n) && n > 0 ? Math.floor(n) : 0;
}

function normalizeStats(v) {
  v = (v && typeof v === "object") ? v : {};
  return {
    made: nonNeg(v.made), sent: nonNeg(v.sent), fallbacks: nonNeg(v.fallbacks),
    lastText: typeof v.lastText === "string" ? v.lastText : "",
    lastAt: nonNeg(v.lastAt)
  };
}

// Stats live in amin.db ("state"/"stats"); a legacy amin.storage
// copy is read once and migrated when the db has nothing yet.
function loadStats() {
  if (statsCache) return statsCache;
  if (dbAvailable()) {
    try {
      var v = amin.db.get("state", "stats");
      if (v && typeof v === "object") { statsCache = normalizeStats(v); return statsCache; }
    } catch (e) { amin.log("qr-maker stats read error: " + e); }
  }
  var legacy = loadJsonStorage("stats");
  if (legacy) {
    statsCache = normalizeStats(legacy);
    if (dbAvailable()) { try { amin.db.put("state", "stats", statsCache); } catch (e) {} }
    return statsCache;
  }
  statsCache = normalizeStats(null);
  return statsCache;
}

function saveStats() {
  if (!statsCache) return;
  var ok = false;
  if (dbAvailable()) { try { ok = amin.db.put("state", "stats", statsCache) === true; } catch (e) {} }
  if (!ok) saveJsonStorage("stats", statsCache);
}

// Runs fn inside a fresh async callback (fresh hook budget).
function budgetTick(fn) {
  var called = false;
  function run() {
    if (called) return;
    called = true;
    fn();
  }
  if (typeof amin.httpGetAsync === "function") {
    try {
      amin.httpGetAsync(BUDGET_TICK_URL, null, function () { run(); });
      return;
    } catch (e) { amin.log("qr-maker budget tick error: " + e); }
  }
  run();
}

function qrUrlFor(text) {
  return QR_API + encodeURIComponent(text);
}

function shortLabel(text) {
  var t = String(text || "").replace(/\s+/g, " ").trim();
  return t.length > 80 ? t.substring(0, 80) + "…" : t;
}

// Everything after the send lives here, under a fresh budget:
// record the outcome, and post the link fallback when needed.
function finishQr(ctx, text, url, sent) {
  try {
    var stats = loadStats();
    if (sent) {
      stats.sent++;
      amin.log("qr-maker sent QR photo for: " + shortLabel(text));
    } else {
      stats.fallbacks++;
      amin.log("qr-maker sendFile unavailable/failed, posting link for: " + shortLabel(text));
      amin.reply(ctx.msg, "🔳 QR code for: " + shortLabel(text) + "\n" + url);
    }
    saveStats();
  } catch (e) { amin.log("qr-maker finish error: " + e); }
}

function onCommand(ctx) {
  try {
    if (String(ctx.command || "").toLowerCase() !== "qr") return;
    var text = (ctx.args || "").trim();
    if (!text) {
      amin.reply(ctx.msg, "Usage: /qr <text or link>");
      return;
    }
    if (text.length > MAX_TEXT) {
      amin.reply(ctx.msg, "⚠️ That text is too long for a QR code (max " + MAX_TEXT + " characters).");
      return;
    }
    var url = qrUrlFor(text);
    var stats = loadStats();
    stats.made++;
    stats.lastText = shortLabel(text);
    stats.lastAt = new Date().getTime();
    saveStats();

    if (typeof amin.sendFile !== "function") {
      finishQr(ctx, text, url, false);
      return;
    }
    var sent = false;
    try {
      sent = amin.sendFile(url, {
        chatId: ctx.chatId,
        type: "photo",
        caption: "QR for: " + shortLabel(text)
      }) === true;
    } catch (e) {
      amin.log("qr-maker sendFile error: " + e);
      sent = false;
    }
    // sendFile was the last substantive action of this invocation;
    // the outcome is handled under a fresh budget window.
    budgetTick(function () { finishQr(ctx, text, url, sent); });
  } catch (e) {
    amin.log("qr-maker onCommand error: " + e);
    try { amin.reply(ctx.msg, "⚠️ QR failed — see the plugin log."); } catch (e2) {}
  }
}

function onPluginAction(actionId) {
  try {
    if (actionId === "usage") {
      amin.toast("In any chat: /qr <text or link> — the QR arrives as a photo");
      return;
    }
    if (actionId === "stats") {
      var stats = loadStats();
      amin.toast("🔳 " + stats.made + " made · 📷 " + stats.sent + " sent · 🔗 " + stats.fallbacks + " link fallback(s)");
      return;
    }
    if (actionId === "clear-stats") {
      statsCache = normalizeStats(null);
      saveStats();
      amin.toast("🧹 QR statistics cleared");
    }
  } catch (e) { amin.log("qr-maker onPluginAction error: " + e); }
}
